-- 每次复盘一条持久任务/正文，离开浏览器不取消生成。
CREATE TABLE `ai_submission_review` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `user_id` bigint NOT NULL,
  `submission_id` bigint NOT NULL,
  `problem_id` bigint NOT NULL,
  `request_id` varchar(64) COLLATE utf8mb4_bin NOT NULL,
  `request_hash` char(64) NOT NULL,
  `parent_review_id` bigint DEFAULT NULL,
  `relation_type` varchar(16) NOT NULL,
  `status` varchar(16) NOT NULL,
  `problem_title` varchar(255) NOT NULL,
  `language` varchar(32) DEFAULT NULL,
  `submission_status` tinyint DEFAULT NULL,
  `score` int DEFAULT NULL,
  `run_time` int DEFAULT NULL,
  `run_memory` int DEFAULT NULL,
  `help_mode` varchar(32) NOT NULL,
  `student_question` varchar(2000) DEFAULT NULL,
  `input_json` mediumtext NOT NULL,
  `code_hash` char(64) NOT NULL,
  `privileged` tinyint NOT NULL DEFAULT 0,
  `answer` mediumtext,
  `error_code` varchar(64) DEFAULT NULL,
  `message` varchar(512) DEFAULT NULL,
  `execution_id` char(36) DEFAULT NULL,
  `model` varchar(255) DEFAULT NULL,
  `service_name` varchar(255) DEFAULT NULL,
  `source_json` text,
  `prompt_tokens` int NOT NULL DEFAULT 0,
  `completion_tokens` int NOT NULL DEFAULT 0,
  `tokens_estimated` tinyint NOT NULL DEFAULT 0,
  `latency_ms` bigint NOT NULL DEFAULT 0,
  `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `start_time` datetime DEFAULT NULL,
  `finish_time` datetime DEFAULT NULL,
  `update_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `active_submission_id` bigint GENERATED ALWAYS AS (CASE WHEN `status` IN ('QUEUED','RUNNING','CANCELLING') THEN `submission_id` ELSE NULL END) STORED,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_review_request` (`user_id`,`request_id`),
  UNIQUE KEY `uk_review_active` (`user_id`,`active_submission_id`),
  KEY `idx_review_user_id` (`user_id`,`id`),
  KEY `idx_review_submission` (`user_id`,`submission_id`,`id`),
  KEY `idx_review_status` (`status`,`start_time`,`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='用户AI提交复盘记录';
